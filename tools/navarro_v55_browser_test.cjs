const {chromium}=require('playwright');
const fs=require('fs'),path=require('path');
(async()=>{
 const result={time:new Date().toISOString(),passed:[],warnings:[],errors:[],samples:[],success:false};
 const browser=await chromium.launch({headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
 const ctx=await browser.newContext({viewport:{width:1280,height:900},acceptDownloads:true});
 const page=await ctx.newPage();
 page.on('pageerror',e=>result.errors.push('JS: '+e.message));
 page.on('console',m=>{
  if(m.type()==='error'&&!/TensorFlow Lite XNNPACK delegate|INFO:/.test(m.text()))result.warnings.push(m.text().slice(0,260));
 });
 try{
  await page.goto('http://localhost:8111/test-foto-v55.html',{waitUntil:'domcontentloaded',timeout:90000});
  const show=page.locator('.nav-visual-trigger:visible').first();
  await show.waitFor({timeout:30000});
  result.passed.push('Botón visible en barra de computadora');
  const choose=page.waitForEvent('filechooser');
  await show.click();
  const picked=await choose;
  const samples=fs.readdirSync('navarro360-movil/assets').filter(x=>/^navarro-publicada-\d+\.jpg$/.test(x));
  const sample=samples.find(x=>x.includes('038753323510'))||samples[0];
  await picked.setFiles(path.resolve('navarro360-movil/assets',sample));
  await page.locator('dialog.nav-visual-dialog[open]').waitFor({timeout:10000});
  result.passed.push('Elegir imagen y abrir resultados');
  await page.waitForFunction(()=>document.querySelectorAll('.nav-visual-item').length>=5,{timeout:90000}).catch(()=>{});
  const count=await page.locator('.nav-visual-item').count();
  const message=await page.locator('.nav-visual-status').textContent();
  result.samples.push({file:sample,count,message,first:(await page.locator('.nav-visual-item').first().textContent().catch(()=>''))?.slice(0,190)});
  if(count<5)throw Error('Sin sugerencias visuales para fotografía de prueba: '+message);
  result.passed.push('Modelo visual devuelve '+count+' opciones');
  const cropArea=page.locator('.nav-visual-croparea');
  if(!await cropArea.isVisible())throw Error('No aparece herramienta de recorte');
  const box=await page.locator('.nav-visual-cropstage').boundingBox();
  if(!box||box.width<40||box.height<40)throw Error('Imagen no disponible para recorte');
  await page.mouse.move(box.x+box.width*.15,box.y+box.height*.15);
  await page.mouse.down();
  await page.mouse.move(box.x+box.width*.85,box.y+box.height*.85,{steps:10});
  await page.mouse.up();
  const cropButton=page.locator('.nav-visual-cropactions button').first();
  if(await cropButton.isDisabled())throw Error('Recorte no habilitado tras seleccionarlo');
  result.passed.push('Arrastrar recorte activa la búsqueda localizada');
  await cropButton.click();
  await page.waitForFunction(()=>{const t=document.querySelector('.nav-visual-status')?.textContent||'';return t.includes('Comparé la imagen')||t.includes('No se pudo completar')},{timeout:90000}).catch(()=>{});
  const after=await page.locator('.nav-visual-status').textContent();
  if(!after.includes('Comparé la imagen'))throw Error('Búsqueda por recorte no concluyó: '+after);
  result.passed.push('Modelo visual analiza recorte sin errores');
  await page.locator('.nav-visual-item button[data-visual-show]').first().click();
  if(await page.locator('dialog.nav-visual-dialog').evaluate(d=>d.open))throw Error('No cerró resultado visual al elegir');
  const code=await page.locator('#search').inputValue();
  if(!/^\d{5,20}$/.test(code))throw Error('El código elegido no se escribió en la búsqueda: '+code);
  result.passed.push('Producto elegido aparece en buscador normal: '+code);
  await page.setViewportSize({width:390,height:844});
  await page.locator('.nav-visual-trigger:visible').first().waitFor();
  result.passed.push('Botón de foto accesible también en móvil');
  result.success=true;
 }catch(e){result.errors.push(String(e.message||e))}
 fs.writeFileSync('test-browser-foto-v55.json',JSON.stringify(result,null,2));
 await browser.close();
 console.log(JSON.stringify(result,null,2));
 if(!result.success)process.exitCode=1;
})();